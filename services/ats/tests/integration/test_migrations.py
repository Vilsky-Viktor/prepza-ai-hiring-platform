from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import text


def test_every_migration_ran_on_a_fresh_database(run):
    from app.storage.db import engine

    async def current():
        async with engine.connect() as connection:
            return (
                await connection.execute(text("SELECT version_num FROM alembic_version"))
            ).scalar()

    assert run(current()) == ScriptDirectory.from_config(Config("alembic.ini")).get_current_head()


def test_candidates_are_indexed_by_email_and_age(run):
    from app.storage.db import engine

    async def indexes():
        async with engine.connect() as connection:
            query = text("SELECT indexname FROM pg_indexes WHERE tablename = 'ats_candidates'")

            return set((await connection.execute(query)).scalars())

    assert {"ix_ats_candidates_email", "ix_ats_candidates_created_at"} <= run(indexes())


def test_the_models_match_the_migrations():
    """What `alembic check` reports: a model changed without its migration, or a migration
    without its model, so the next autogenerated migration would undo it."""
    command.check(Config("alembic.ini"))


def test_a_migration_waits_only_so_long_for_a_lock():
    from prepza_common.constants import MIGRATION_LOCK_TIMEOUT
    from prepza_common.db import migration_engine

    from app.config.settings import settings

    engine = migration_engine(settings.database_url)

    try:
        with engine.connect() as connection:
            waits = connection.execute(text("SHOW lock_timeout")).scalar()
    finally:
        engine.dispose()

    assert waits == MIGRATION_LOCK_TIMEOUT


def test_postgres_ends_a_transaction_left_idle(run):
    from app.storage.db import engine

    async def setting():
        async with engine.connect() as connection:
            query = text("SHOW idle_in_transaction_session_timeout")

            return (await connection.execute(query)).scalar()

    # IDLE_IN_TRANSACTION_TIMEOUT, as Postgres shows it.
    assert run(setting()) == "1min"
