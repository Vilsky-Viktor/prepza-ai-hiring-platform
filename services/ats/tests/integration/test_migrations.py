def test_postgres_stops_a_runaway_statement(run):
    from app.storage.db import engine

    async def outcome():
        async with engine.connect() as connection:
            limit = (await connection.execute(text("SHOW statement_timeout"))).scalar()
            # A job that needs longer lowers it for its transaction; here, below the sleep.
            await connection.execute(text("SET LOCAL statement_timeout = '100ms'"))

            try:
                await connection.execute(text("SELECT pg_sleep(1)"))
            except DBAPIError as error:
                return limit, type(error.orig).__name__

            return limit, None

    # STATEMENT_TIMEOUT, as Postgres shows it.
    assert run(outcome()) == ("1min", "QueryCanceled")


def test_a_table_breaking_a_database_rule_is_named():
    from prepza_common.schema_rules import problems

    from app.config.settings import settings

    engine = create_engine(sqlalchemy_url(settings.database_url))
    table = f"rule_check_{uuid.uuid4().hex}"

    try:
        with engine.begin() as connection:
            connection.execute(text(f"CREATE TABLE {table} (created_at timestamptz)"))

        found = problems(settings.database_url)
    finally:
        with engine.begin() as connection:
            connection.execute(text(f"DROP TABLE IF EXISTS {table}"))

        engine.dispose()

    assert found == [f"created_at without a database default: {table}"]
