def test_every_migration_ran_on_a_fresh_database(run):
    from site_content.core.db import engine

    async def current():
        async with engine.connect() as connection:
            return (
                await connection.execute(text("SELECT version_num FROM alembic_version"))
            ).scalar()

    assert run(current()) == ScriptDirectory.from_config(Config("alembic.ini")).get_current_head()


def test_the_models_match_the_migrations():
    """What `alembic check` reports: a model changed without its migration, or a migration
    without its model, so the next autogenerated migration would undo it. Run in a process of its
    own, so a model the other tests imported can't hide one migrations/env.py leaves out."""
    checked = subprocess.run(
        [sys.executable, "-m", "alembic", "check"], capture_output=True, text=True, check=False
    )

    assert checked.returncode == 0, checked.stdout + checked.stderr


