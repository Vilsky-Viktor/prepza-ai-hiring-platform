def test_postgres_stops_a_runaway_statement(run):
    from site_content.core.db import engine

    async def outcome():
        async with engine.connect() as connection:
            limit = (await connection.execute(text("SHOW statement_timeout"))).scalar()
            # A job that needs longer lowers it for its transaction; here, below the sleep.
            await connection.execute(text("SET LOCAL statement_timeout = '100ms'"))

            try:
                await connection.execute(text("SELECT pg_sleep(1)"))
            except DBAPIError as error:
                return limit, type(error.orig).__name__

            return limit, None

    # STATEMENT_TIMEOUT, as Postgres shows it.
    assert run(outcome()) == ("1min", "QueryCanceled")


def test_a_table_breaking_a_database_rule_is_named():
    from testee_common.db.schema_rules import problems

    from site_content.config import settings

    engine = create_engine(sqlalchemy_url(settings.database_url))
    table = f"rule_check_{uuid.uuid4().hex}"
    columns = (
        "id uuid PRIMARY KEY, created_at timestamp, data json, number serial,"
        f" parent_id uuid REFERENCES {table} (id)"
    )

    try:
        with engine.begin() as connection:
            connection.execute(text(f"CREATE TABLE {table} ({columns})"))

        found = problems(settings.database_url)
    finally:
        with engine.begin() as connection:
            connection.execute(text(f"DROP TABLE IF EXISTS {table}"))

        engine.dispose()

    assert found == sorted(
        [
            f"a foreign key without ON DELETE: {table}.{table}_parent_id_fkey",
            f"a foreign key without an index: {table}.{table}_parent_id_fkey",
            f"created_at without a database default: {table}",
            f"a serial key instead of an identity column: {table}.number",
            f"json instead of jsonb, char(n) or money: {table}.data",
            f"timestamp without a time zone: {table}.created_at",
        ]
    )


def test_a_tenants_child_table_without_its_company_is_named():
    from testee_common.db.schema_rules import problems

    from site_content.config import settings

    engine = create_engine(sqlalchemy_url(settings.database_url))
    parent, child = (f"rule_{name}_{uuid.uuid4().hex[:8]}" for name in ("parent", "child"))
    tables = (
        f"CREATE TABLE {parent} (id uuid PRIMARY KEY, company_id uuid NOT NULL)",
        (
            f"CREATE TABLE {child} (id uuid PRIMARY KEY, "
            f"parent_id uuid REFERENCES {parent} ON DELETE CASCADE, "
            "created_at timestamptz DEFAULT now())"
        ),
        f"CREATE INDEX ON {child} (parent_id)",
    )

    try:
        with engine.begin() as connection:
            for statement in tables:
                connection.execute(text(statement))

        found = problems(settings.database_url)
    finally:
        with engine.begin() as connection:
            connection.execute(text(f"DROP TABLE IF EXISTS {child}, {parent}"))

        engine.dispose()

    assert found == [f"a tenant's child table without company_id: {child}"]
