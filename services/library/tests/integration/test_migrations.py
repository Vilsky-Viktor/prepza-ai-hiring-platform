import subprocess
import sys

from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import text


def test_every_migration_ran_on_a_fresh_database(run):
    from library.core.db import engine

    async def current():
        async with engine.connect() as connection:
            return (
                await connection.execute(text("SELECT version_num FROM alembic_version"))
            ).scalar()

    assert run(current()) == ScriptDirectory.from_config(Config("alembic.ini")).get_current_head()


def test_the_models_match_the_migrations():
    """What `alembic check` reports: a model changed without its migration, or a migration
    without its model, so the next autogenerated migration would undo it. Run in a process of its
    own, so a model the other tests imported can't hide one migrations/env.py leaves out."""
    checked = subprocess.run(
        [sys.executable, "-m", "alembic", "check"], capture_output=True, text=True, check=False
    )

    assert checked.returncode == 0, checked.stdout + checked.stderr


def test_the_tables_follow_the_database_rules():
    """What `.claude/rules/database.md` asks of every table (testee_common.db.schema_rules)."""
    from testee_common.db.schema_rules import problems

    from library.config import settings

    assert problems(settings.database_url) == []


def test_the_models_name_constraints_and_indexes_as_the_database_does():
    """So a migration can drop or rename one by its name (the naming convention, models/base.py)."""
    from testee_common.db.schema_rules import misnamed

    import library.models
    from library.config import settings

    assert misnamed(settings.database_url, library.models) == []


def test_every_check_allows_what_its_model_allows():
    """A value added to a closed set in the code changes its CHECK in a migration too."""
    from testee_common.db.schema_rules import stale_checks

    import library.models
    from library.config import settings

    assert stale_checks(settings.database_url, library.models) == []
